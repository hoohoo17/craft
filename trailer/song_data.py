def _melody(line, idx):
    """가사 글자 수에 맞춰 음 높이와 박자를 만든다.

    글자가 적으면 한 글자를 길게 끌고, 많으면 짧게 끊어서
    누가 부르든 4박자(1.5초) 안에 들어가게 한다.
    """
    syl = [c for c in line if c != " "]
    n = len(syl)
    if n >= 8:
        step = SEG_BEATS / n
    else:
        step = max(0.5, min(1.0, 3.0 / n))
    last = max(step, min(2.0, SEG_BEATS - step * (n - 1)))
    durs = [step] * (n - 1) + [last]
    shape = SHAPES[idx % len(SHAPES)]
    if n == 1:
        notes = [60 + shape[0]]
    else:
        notes = [60 + shape[round(i * (len(shape) - 1) / (n - 1))] for i in range(n)]
    return syl, notes, durs


