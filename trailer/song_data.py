def notes_of(s):
    """(가사, 음, 시작박, 길이박) 목록"""
    out, b = [], 0.0
    for syl, note, dur in zip(s["syl"], s["note"], s["dur"]):
        out.append((syl, note, b, dur))
        b += dur
    return out


def spaces_of(s):
    """몇 번째 글자 뒤에서 띄어 쓰는지 알려 준다."""
    out, i = set(), -1
    for ch in s["line"]:
        if ch == " ":
            out.add(i)
        else:
            i += 1
    return out
